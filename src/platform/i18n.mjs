export const TABLES = { fr: FR, en: EN }
let lang = 'fr'
export function resolveLang(pref, nav) {
if (pref === 'fr' || pref === 'en') return pref
return typeof nav === 'string' && /^fr\b/i.test(nav) ? 'fr' : 'en'
}
export function setLang(l) { lang = l === 'en' ? 'en' : 'fr'; return lang }
export function getLang() { return lang }
export function t(key, vars) {
let s = TABLES[lang][key]
if (s === undefined) s = TABLES.fr[key]
if (s === undefined) return key
if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])))
return s
}
export function fmtNumber(n) { return new Intl.NumberFormat(lang).format(n) }
